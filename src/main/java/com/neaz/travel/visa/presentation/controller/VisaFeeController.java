package com.neaz.travel.visa.presentation.controller;

import com.neaz.travel.visa.application.query.VisaFeeQueryService;
import com.neaz.travel.visa.common.model.ApiResponse;
import com.neaz.travel.visa.presentation.dto.VisaFeeRequest;
import com.neaz.travel.visa.presentation.dto.VisaFeeResponse;
import com.neaz.travel.visa.presentation.mapper.VisaFeeMapper;
import jakarta.validation.Valid;
import org.springframework.http.HttpStatus;
import org.springframework.http.ResponseEntity;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.ModelAttribute;
import org.springframework.web.bind.annotation.RequestMapping;
import org.springframework.web.bind.annotation.RestController;

/**
 * Exposes structured, source-backed visa fees over HTTP. Fees are served from
 * PostgreSQL, never generated by the LLM. When no official fee is recorded for
 * the requested scope (nor a {@code GENERAL} fallback), the response is 404
 * with the standard insufficient-information message.
 */
@RestController
@RequestMapping("/api/v1/visa")
public class VisaFeeController {

    static final String NO_OFFICIAL_FEE_MESSAGE = "I couldn't find sufficient official information.";

    private final VisaFeeQueryService visaFeeQueryService;
    private final VisaFeeMapper visaFeeMapper;

    public VisaFeeController(VisaFeeQueryService visaFeeQueryService, VisaFeeMapper visaFeeMapper) {
        this.visaFeeQueryService = visaFeeQueryService;
        this.visaFeeMapper = visaFeeMapper;
    }

    @GetMapping("/fees")
    public ResponseEntity<ApiResponse<VisaFeeResponse>> getFee(@Valid @ModelAttribute VisaFeeRequest request) {
        return visaFeeQueryService.findFee(request.passport(), request.destination(), request.visaType())
                .map(visaFeeMapper::toResponse)
                .map(response -> ResponseEntity.ok(ApiResponse.success(response)))
                .orElseGet(() -> ResponseEntity.status(HttpStatus.NOT_FOUND)
                        .body(ApiResponse.error(NO_OFFICIAL_FEE_MESSAGE)));
    }
}
